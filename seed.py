def run_seed(app, db):
    from models import Company, Category, Tool

    with app.app_context():
        db.create_all()

        # Categories
        cat_map = {}
        for name, icon, desc, sort in CATEGORIES:
            existing = Category.query.filter_by(name=name).first()
            if existing:
                cat_map[name] = existing
                continue
            c = Category(name=name, slug=slugify(name), icon=icon, description=desc, sort_order=sort)
            db.session.add(c)
            cat_map[name] = c
        db.session.commit()

        # Companies
        comp_map = {}
        for name, desc, website, founded, hq in COMPANIES:
            existing = Company.query.filter_by(name=name).first()
            if existing:
                comp_map[name] = existing
                continue
            c = Company(name=name, slug=slugify(name), description=desc, website=website, founded=founded, hq=hq)
            db.session.add(c)
            comp_map[name] = c
        db.session.commit()

        # Tools
        for t in TOOLS:
            existing = Tool.query.filter_by(slug=t["slug"]).first()
            if existing:
                continue
            company = comp_map.get(t["company"])
            if not company:
                print(f"  ! Skipping {t['name']} — unknown company '{t['company']}'")
                continue
            tool = Tool(
                company_id=company.id,
                name=t["name"],
                slug=t["slug"],
                tagline=t["tagline"],
                description=t["description"],
                pricing_model=t["pricing_model"],
                pricing_details=t["pricing_details"],
                strengths=t["strengths"],
                weaknesses=t["weaknesses"],
                best_for=t["best_for"],
                website=t["website"],
                launched=t["launched"],
                featured=t.get("featured", False),
            )
            tool.categories = [cat_map[c] for c in t["categories"] if c in cat_map]
            db.session.add(tool)
        db.session.commit()

        print(f"  ✓ {Category.query.count()} categories")
        print(f"  ✓ {Company.query.count()} companies")
        print(f"  ✓ {Tool.query.count()} tools")
